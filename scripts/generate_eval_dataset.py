def main() -> None:
    """Generate stable IDs while preserving every reviewed family oracle."""

    source = json.loads(FAMILIES_PATH.read_text(encoding="utf-8"))
    families = {case["case_id"]: case for case in source["cases"]}
    if set(families) != set(TEXT_VARIANTS):
        raise RuntimeError("family templates and text variants are out of sync")

    cases: list[dict[str, object]] = []
    channels = ("email", "call_transcript", "portal")
    for family_id, variants in TEXT_VARIANTS.items():
        template = families[family_id]
        for index, text in enumerate(variants, start=1):
            case = copy.deepcopy(template)
            suffix = "" if index == 1 else f"_{index:02d}"
            case["case_id"] = f"{family_id}{suffix}"
            case["title"] = f"{template['title']} · вариант {index:02d}"
            case["description"] = (
                f"{template['description']} Языковой вариант {index:02d}."
            )
            request = case["request"]
            request["source_request_id"] = f"eval-{family_id}-{index:03d}"
            request["channel"] = channels[(index - 1) % len(channels)]
            request["text"] = text
            if family_id == "attachment_injection":
                request["attachment_text"] = ATTACHMENT_VARIANTS[index - 1]
            cases.append(case)

    if len(cases) != 100:
        raise RuntimeError(f"expected 100 generated cases, got {len(cases)}")
    positive = sum(case["polarity"] == "positive" for case in cases)
    if positive != 50:
        raise RuntimeError(f"expected 50 positive cases, got {positive}")

    dataset = {
        "name": "Регрессия триажа сервисных обращений — 100 кейсов",
        "version": "3.0.0",
        "description": (
            "100 размеченных языковых вариантов: 50 позитивных и 50 негативных; "
            "сущности, SLA, повторы, capacity, безопасность и отказоустойчивое поведение."
        ),
        "cases": cases,
    }
    OUTPUT_PATH.write_text(
        json.dumps(dataset, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
